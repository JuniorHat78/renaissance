#!/usr/bin/env node
"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("playwright");

const SLOW_3G = {
  offline: false,
  latency: 400,
  downloadThroughput: Math.floor((400 * 1024) / 8),
  uploadThroughput: Math.floor((400 * 1024) / 8),
  connectionType: "cellular3g"
};

function parseArgs(argv) {
  const options = {
    base: process.env.RENAISSANCE_BASE_URL || "http://127.0.0.1:4187",
    artifacts: path.join("qa", "transition-evidence")
  };

  for (let index = 2; index < argv.length; index += 1) {
    const token = argv[index];
    if (token === "--base" && argv[index + 1]) {
      options.base = argv[index + 1];
      index += 1;
    } else if (token === "--artifacts" && argv[index + 1]) {
      options.artifacts = argv[index + 1];
      index += 1;
    }
  }

  options.base = options.base.replace(/\/+$/, "");
  options.artifacts = path.resolve(process.cwd(), options.artifacts);
  return options;
}

function ensureDir(dirPath) {
  fs.mkdirSync(dirPath, { recursive: true });
}

function runSlug() {
  return new Date().toISOString().replace(/[:.]/g, "-");
}

function fileSlug(value) {
  return String(value || "scenario").replace(/[^a-z0-9]+/gi, "-").replace(/^-+|-+$/g, "").toLowerCase();
}

function writeJson(filePath, value) {
  fs.writeFileSync(filePath, JSON.stringify(value, null, 2) + "\n", "utf8");
}

function writeMarkdown(filePath, report) {
  const lines = [
    "# Transition Evidence",
    "",
    "Generated by `scripts/tests/transition-evidence-regression.js`.",
    "",
    "## Summary",
    "",
    "| Scenario | Status | Click To Ready | Notes |",
    "| --- | --- | ---: | --- |"
  ];

  for (const scenario of report.scenarios) {
    const clickToReady = Number.isFinite(scenario.clickToReadyMs)
      ? String(Math.round(scenario.clickToReadyMs)) + "ms"
      : "";
    lines.push(
      "| " +
      scenario.name +
      " | " +
      scenario.status +
      " | " +
      clickToReady +
      " | " +
      (scenario.notes || "") +
      " |"
    );
  }

  lines.push("", "## Artifacts", "");
  for (const scenario of report.scenarios) {
    lines.push("### " + scenario.name, "");
    for (const artifact of scenario.artifacts || []) {
      lines.push("- `" + path.basename(artifact) + "`");
    }
    if (scenario.samples && scenario.samples.length) {
      lines.push("- samples: " + String(scenario.samples.length));
    }
    lines.push("");
  }

  fs.writeFileSync(filePath, lines.join("\n"), "utf8");
}

async function waitForPageReady(page) {
  await page.waitForFunction(() => {
    const root = document.documentElement;
    return root.classList.contains("page-transition-ready") &&
      !root.classList.contains("page-transition-prep") &&
      !root.classList.contains("page-transition-out") &&
      root.getAttribute("aria-busy") !== "true";
  }, null, { timeout: 30000 });
}

async function waitForSectionReady(page) {
  await page.waitForSelector("#section-content p", { timeout: 30000 });
  await page.waitForFunction(() => {
    const title = document.getElementById("section-title");
    const layout = document.querySelector(".reader-layout");
    return title &&
      !/loading/i.test(String(title.textContent || "")) &&
      (!layout || !layout.classList.contains("is-section-turning"));
  }, null, { timeout: 30000 });
}

async function visualState(page) {
  return page.evaluate(() => {
    const root = document.documentElement;
    const main = document.querySelector("main");
    const article = document.querySelector(".chapter-article");
    const layout = document.querySelector(".reader-layout");
    const mainStyle = main ? window.getComputedStyle(main) : null;
    const articleStyle = article ? window.getComputedStyle(article) : null;
    const bodyStyle = window.getComputedStyle(document.body);
    const mark = document.querySelector('mark[data-auto-highlight="1"]');
    const markRect = mark ? mark.getBoundingClientRect() : null;

    return {
      time: Math.round(performance.now()),
      url: window.location.href,
      title: String((document.getElementById("section-title") || document.querySelector("h1"))?.textContent || "").trim(),
      bodyOpacity: Number.parseFloat(bodyStyle.opacity || "0"),
      mainOpacity: mainStyle ? Number.parseFloat(mainStyle.opacity || "0") : 1,
      articleOpacity: articleStyle ? Number.parseFloat(articleStyle.opacity || "0") : null,
      rootClasses: root.className,
      readerClasses: layout ? layout.className : "",
      busy: root.getAttribute("aria-busy"),
      textLength: main ? String(main.textContent || "").trim().length : 0,
      markText: mark ? String(mark.textContent || "").replace(/\s+/g, " ").trim() : "",
      markTop: markRect ? markRect.top : null,
      markBottom: markRect ? markRect.bottom : null,
      viewportHeight: window.innerHeight
    };
  });
}

async function sampleFor(page, durationMs, intervalMs) {
  const started = Date.now();
  const samples = [];
  while (Date.now() - started <= durationMs) {
    samples.push(await visualState(page));
    await page.waitForTimeout(intervalMs);
  }
  return samples;
}

function assertReadable(state, label) {
  assert.ok(state.textLength > 0, label + " should contain readable text");
  assert.ok(state.bodyOpacity > 0.9, label + " body should stay visible");
  assert.ok(state.mainOpacity > 0.9, label + " main content should stay visible");
  assert.notEqual(state.busy, "true", label + " should not leave root aria-busy=true");
}

async function withContext(browser, outputDir, name, options, callback) {
  const scenarioDir = path.join(outputDir, fileSlug(name));
  const videoDir = path.join(scenarioDir, "video");
  ensureDir(videoDir);

  const context = await browser.newContext({
    locale: "en-US",
    timezoneId: "UTC",
    viewport: { width: 1440, height: 1000 },
    colorScheme: "light",
    reducedMotion: "no-preference",
    recordVideo: { dir: videoDir, size: { width: 1280, height: 720 } },
    ...(options && options.context ? options.context : {})
  });
  const page = await context.newPage();
  const tracePath = path.join(scenarioDir, "trace.zip");
  const artifacts = [tracePath];
  let video = null;

  await context.tracing.start({ screenshots: true, snapshots: true, sources: true });
  try {
    if (options && options.slowNetwork) {
      const client = await context.newCDPSession(page);
      await client.send("Network.enable");
      await client.send("Network.emulateNetworkConditions", SLOW_3G);
    }

    video = page.video();
    const result = await callback(page, scenarioDir);
    await context.tracing.stop({ path: tracePath });
    await context.close();
    if (video) {
      artifacts.push(await video.path());
    }
    return {
      ...result,
      artifacts: artifacts.concat(result.artifacts || [])
    };
  } catch (error) {
    try {
      await page.screenshot({ path: path.join(scenarioDir, "failure.png"), fullPage: true });
      artifacts.push(path.join(scenarioDir, "failure.png"));
    } catch (_screenshotError) {
      // keep original failure
    }
    try {
      await context.tracing.stop({ path: tracePath });
    } catch (_traceError) {
      // keep original failure
    }
    try {
      await context.close();
    } catch (_closeError) {
      // keep original failure
    }
    error.artifacts = artifacts;
    throw error;
  }
}

async function searchResultArrival(page, scenarioDir, base) {
  const beforePath = path.join(scenarioDir, "before-search-results.png");
  const afterPath = path.join(scenarioDir, "after-reader-highlight.png");
  const samplesPath = path.join(scenarioDir, "samples.json");

  await page.goto(base + "/search.html?q=verdun", { waitUntil: "domcontentloaded", timeout: 30000 });
  await waitForPageReady(page);
  await page.waitForSelector("#search-page-results .result-card a[href*='section.html']", { timeout: 30000 });
  await page.screenshot({ path: beforePath, fullPage: true });

  const clickState = await page.evaluate(() => {
    const link = document.querySelector("#search-page-results .result-card a[href*='section.html']");
    const started = performance.now();
    link.click();
    return {
      out: document.documentElement.classList.contains("page-transition-out"),
      source: Boolean(document.querySelector(".is-page-transition-source")),
      delay: window.RenaissancePageTransition && window.RenaissancePageTransition.outDelayMs,
      revealMode: window.RenaissancePageTransition && window.RenaissancePageTransition.revealMode,
      syncMs: performance.now() - started
    };
  });

  assert.equal(clickState.out, true, "search result click should mark page outgoing immediately");
  assert.equal(clickState.source, true, "search result click should mark source immediately");
  assert.ok(clickState.delay <= 75, "outgoing delay should remain below tap-latency threshold");
  assert.equal(clickState.revealMode, "immediate", "destination reveal should remain immediate");

  const started = Date.now();
  await page.waitForURL(/section\.html/, { waitUntil: "domcontentloaded", timeout: 30000 });
  await waitForPageReady(page);
  await page.waitForSelector('mark[data-auto-highlight="1"]', { timeout: 30000 });
  await page.waitForTimeout(420);
  const clickToReadyMs = Date.now() - started;

  const state = await visualState(page);
  assertReadable(state, "search-result arrival");
  assert.ok(state.markText.toLowerCase().includes("verdun"), "arrival highlight should match the query");
  assert.ok(
    state.markTop !== null &&
      state.markBottom !== null &&
      state.markBottom > 0 &&
      state.markTop < state.viewportHeight,
    "arrival highlight should be visible in the viewport"
  );

  const samples = await sampleFor(page, 240, 60);
  writeJson(samplesPath, samples);
  await page.screenshot({ path: afterPath, fullPage: true });

  return {
    clickToReadyMs,
    samples,
    notes: "Search result opened reader with visible query highlight.",
    artifacts: [beforePath, afterPath, samplesPath]
  };
}

async function sectionTurn(page, scenarioDir, base) {
  const beforePath = path.join(scenarioDir, "before-section-next.png");
  const afterPath = path.join(scenarioDir, "after-section-next.png");
  const samplesPath = path.join(scenarioDir, "samples.json");

  await page.goto(base + "/section.html?essay=etching-god-into-sand&section=1", {
    waitUntil: "domcontentloaded",
    timeout: 30000
  });
  await waitForPageReady(page);
  await waitForSectionReady(page);
  await page.screenshot({ path: beforePath, fullPage: true });

  const clickState = await page.evaluate(() => {
    const link = document.getElementById("next-link");
    const title = document.getElementById("section-title");
    const started = performance.now();
    link.click();
    const layout = document.querySelector(".reader-layout");
    return {
      beforeTitle: String(title && title.textContent || "").trim(),
      queued: Boolean(layout && layout.classList.contains("is-section-queued")),
      busy: document.documentElement.getAttribute("aria-busy"),
      syncMs: performance.now() - started
    };
  });

  assert.equal(clickState.queued, true, "section click should set queued feedback immediately");
  assert.equal(clickState.busy, "true", "section click should mark the route busy immediately");

  const started = Date.now();
  const samples = [];
  while (Date.now() - started < 1800) {
    samples.push(await visualState(page));
    const changed = samples[samples.length - 1].title && samples[samples.length - 1].title !== clickState.beforeTitle;
    if (changed) {
      break;
    }
    await page.waitForTimeout(50);
  }

  await page.waitForFunction((beforeTitle) => {
    const title = document.getElementById("section-title");
    return title && String(title.textContent || "").trim() !== beforeTitle;
  }, clickState.beforeTitle, { timeout: 30000 });
  await waitForSectionReady(page);
  await page.waitForTimeout(320);
  const clickToReadyMs = Date.now() - started;

  samples.push(...await sampleFor(page, 240, 60));
  writeJson(samplesPath, samples);

  const state = await visualState(page);
  assertReadable(state, "section next arrival");
  assert.ok(!state.readerClasses.includes("is-section-turning"), "section turn class should clear");
  assert.notEqual(state.busy, "true", "section turn should clear root busy state");
  await page.screenshot({ path: afterPath, fullPage: true });

  return {
    clickToReadyMs,
    samples,
    notes: "Section next stayed readable and cleared transition state.",
    artifacts: [beforePath, afterPath, samplesPath]
  };
}

async function reducedMotionSectionTurn(page, scenarioDir, base) {
  const afterPath = path.join(scenarioDir, "reduced-motion-after-next.png");
  await page.goto(base + "/section.html?essay=etching-god-into-sand&section=1", {
    waitUntil: "domcontentloaded",
    timeout: 30000
  });
  await waitForPageReady(page);
  await waitForSectionReady(page);

  const beforeTitle = await page.textContent("#section-title");
  const started = Date.now();
  await page.click("#next-link");
  await page.waitForFunction((title) => {
    const current = document.getElementById("section-title");
    return current && String(current.textContent || "").trim() !== String(title || "").trim();
  }, beforeTitle, { timeout: 30000 });
  await waitForSectionReady(page);
  const clickToReadyMs = Date.now() - started;
  const state = await visualState(page);
  assertReadable(state, "reduced-motion section next");
  await page.screenshot({ path: afterPath, fullPage: true });

  return {
    clickToReadyMs,
    samples: [state],
    notes: "Reduced-motion section navigation settled without hidden content.",
    artifacts: [afterPath]
  };
}

async function slowNetworkSectionTurn(page, scenarioDir, base) {
  const afterPath = path.join(scenarioDir, "slow-network-after-next.png");
  const samplesPath = path.join(scenarioDir, "samples.json");

  await page.goto(base + "/section.html?essay=etching-god-into-sand&section=1", {
    waitUntil: "domcontentloaded",
    timeout: 30000
  });
  await waitForPageReady(page);
  await waitForSectionReady(page);

  const beforeTitle = await page.textContent("#section-title");
  const queued = await page.evaluate(() => {
    document.getElementById("next-link").click();
    const layout = document.querySelector(".reader-layout");
    return Boolean(layout && layout.classList.contains("is-section-queued"));
  });
  assert.equal(queued, true, "slow-network click should still show queued feedback immediately");

  const started = Date.now();
  const samples = [];
  while (Date.now() - started < 2400) {
    samples.push(await visualState(page));
    const changed = samples[samples.length - 1].title && samples[samples.length - 1].title !== String(beforeTitle || "").trim();
    if (changed) {
      break;
    }
    await page.waitForTimeout(120);
  }

  await page.waitForFunction((title) => {
    const current = document.getElementById("section-title");
    return current && String(current.textContent || "").trim() !== String(title || "").trim();
  }, beforeTitle, { timeout: 30000 });
  await waitForSectionReady(page);
  const clickToReadyMs = Date.now() - started;
  samples.push(...await sampleFor(page, 360, 90));
  writeJson(samplesPath, samples);

  const state = await visualState(page);
  assertReadable(state, "slow-network section next");
  await page.screenshot({ path: afterPath, fullPage: true });

  return {
    clickToReadyMs,
    samples,
    notes: "Slow-network section next completed with immediate queued feedback.",
    artifacts: [afterPath, samplesPath]
  };
}

async function runScenario(browser, outputDir, name, options, callback) {
  try {
    const result = await withContext(browser, outputDir, name, options, callback);
    console.log("PASS " + name + " (" + Math.round(result.clickToReadyMs || 0) + "ms)");
    return {
      name,
      status: "pass",
      ...result
    };
  } catch (error) {
    console.error("FAIL " + name + "\n  " + (error && error.message ? error.message : String(error)));
    return {
      name,
      status: "fail",
      notes: error && error.message ? error.message : String(error),
      artifacts: error.artifacts || []
    };
  }
}

async function main() {
  const options = parseArgs(process.argv);
  ensureDir(options.artifacts);
  const outputDir = path.join(options.artifacts, "run-" + runSlug());
  ensureDir(outputDir);

  const browser = await chromium.launch({ headless: true });
  const scenarios = [];

  scenarios.push(await runScenario(
    browser,
    outputDir,
    "search result arrival",
    {},
    (page, scenarioDir) => searchResultArrival(page, scenarioDir, options.base)
  ));
  scenarios.push(await runScenario(
    browser,
    outputDir,
    "section next turn",
    {},
    (page, scenarioDir) => sectionTurn(page, scenarioDir, options.base)
  ));
  scenarios.push(await runScenario(
    browser,
    outputDir,
    "reduced motion section next",
    { context: { reducedMotion: "reduce" } },
    (page, scenarioDir) => reducedMotionSectionTurn(page, scenarioDir, options.base)
  ));
  scenarios.push(await runScenario(
    browser,
    outputDir,
    "slow network section next",
    { slowNetwork: true },
    (page, scenarioDir) => slowNetworkSectionTurn(page, scenarioDir, options.base)
  ));

  await browser.close();

  const report = {
    base: options.base,
    generatedAt: new Date().toISOString(),
    outputDir,
    scenarios
  };
  writeJson(path.join(outputDir, "report.json"), report);
  writeMarkdown(path.join(outputDir, "report.md"), report);

  const failures = scenarios.filter((scenario) => scenario.status !== "pass");
  if (failures.length > 0) {
    console.error("\nTransition evidence failures:");
    failures.forEach((failure) => console.error("- " + failure.name + ": " + failure.notes));
    process.exit(1);
  }

  console.log("Transition evidence written to " + outputDir);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
